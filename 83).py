# 83) Explain Exception handling? What is an Error in Python?
#
# --> Exception handling is a mechanism in Python to handle runtime errors or exceptional
#     conditions that may arise during the execution of a program.
#
# --> An error in Python is an issue that occurs when the program is executed,
#     which leads to a failure in the program's normal operation. Errors are typically
#     categorized into syntax errors and runtime errors.